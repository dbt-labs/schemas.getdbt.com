#!/usr/bin/env python3
"""Build the HTML for the info schema from the raw files in dbt/info-schema/.

Run by the sync workflow in dbt-labs/fs after it copies in the raw files, so one
PR carries both. Input, generated by `cargo xtask info-schema-docs` (never edited
by hand):
  dbt/info-schema/index.json
  dbt/info-schema/v1.json              every table in one schema
  dbt/info-schema/<table>/v1.json
  dbt/info-schema/erd.mmd, erd-<domain>.mmd

Output:
  dbt/info-schema/v1/index.html (+ css, js)            json-schema-for-humans
  dbt/info-schema/<table>/v1/index.html (+ css, js)    json-schema-for-humans
  dbt/info-schema/erd/index.html, erd/<domain>/index.html   Mermaid ERDs
  the "Info Schema" section of the root index.html

Run from anywhere: `make info_schema_html`. Needs `json-schema-for-humans` 1.5.1.
"""

import html
import json
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DBT = REPO / "dbt"
INFO = DBT / "info-schema"
ROOT_PAGE = REPO / "index.html"

# Pinned. The site CSP allows scripts from any https host (see vercel.json).
MERMAID_URL = "https://cdn.jsdelivr.net/npm/mermaid@11.4.1/dist/mermaid.esm.min.mjs"
PANZOOM_URL = "https://cdn.jsdelivr.net/npm/svg-pan-zoom@3.6.1/dist/svg-pan-zoom.min.js"
ERD_TEMPLATE = Path(__file__).with_name("erd_page.html")

START = "<!-- info-schema:start -->"
END = "<!-- info-schema:end -->"

def load_index() -> dict:
    return json.loads((INFO / "index.json").read_text())


def remove_stale_tables(index: dict) -> None:
    """Drop directories of tables that left the index.

    The sync deletes a removed table's JSON but keeps the HTML it excludes
    from `--delete`, so a leftover directory holds only generated files.
    """
    keep = {t["name"] for t in index["tables"]} | {v["name"] for v in index["versions"]} | {"erd"}
    for path in INFO.iterdir():
        if path.is_dir() and path.name not in keep:
            shutil.rmtree(path)


def render_schema_page(schema: Path, out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    # No footer: it carries the generation date, which would change every page
    # on every run.
    subprocess.run(
        ["generate-schema-doc", "--config", "with_footer=false", str(schema), str(out)],
        check=True,
    )


def build_schema_pages(index: dict) -> None:
    for table in index["tables"]:
        for version in table["versions"]:
            render_schema_page(
                INFO / table["name"] / f"{version}.json",
                INFO / table["name"] / version / "index.html",
            )
    for version in index["versions"]:
        render_schema_page(
            INFO / f"{version['name']}.json", INFO / version["name"] / "index.html"
        )


def erd_dir(name: str) -> Path:
    """Page directory of a diagram. The overview is the ERD landing page."""
    return INFO / "erd" if name == "overview" else INFO / "erd" / name


def build_erd_pages(index: dict) -> None:
    """One page per diagram.

    Mermaid keys entity elements by table name, and the diagrams share table
    names, so rendering several on one page makes them overwrite each other.
    """
    # Stale per-domain pages go; the overview page is rewritten below.
    shutil.rmtree(INFO / "erd", ignore_errors=True)
    for diagram in index["diagrams"]:
        name = diagram["name"]
        out = erd_dir(name) / "index.html"
        out.parent.mkdir(parents=True, exist_ok=True)
        up = "../" * len(out.relative_to(REPO).parts[:-1])  # to the repo root
        nav = " ".join(
            f'<a href="{up}dbt/info-schema/erd/'
            f'{"" if d["name"] == "overview" else d["name"] + "/"}index.html"'
            f'{" aria-current=page" if d["name"] == name else ""}>{html.escape(d["name"])}</a>'
            for d in index["diagrams"]
        )
        source = (DBT / diagram["path"]).read_text()
        page = ERD_TEMPLATE.read_text()
        for token, value in {
            "__NAME__": html.escape(name),
            "__UP__": up,
            "__NAV__": nav,
            "__SOURCE__": html.escape(source),
            "__MERMAID_URL__": MERMAID_URL,
            "__PANZOOM_URL__": PANZOOM_URL,
        }.items():
            page = page.replace(token, value)
        out.write_text(page)


def version_key(version: str) -> int:
    return int(version.lstrip("v"))


def root_section(index: dict) -> str:
    """Tables grouped by version, newest first, like the other artifacts.

    A version heading links to the page and the raw file of the whole schema;
    each table has its own page and raw file.
    """
    versions = sorted(
        (v["name"] for v in index["versions"]), key=version_key, reverse=True
    )
    lines = [START, "    <h3>Info Schema</h3>"]
    for version in versions:
        lines += [
            f'    <h4><a href="dbt/info-schema/{version}/index.html">{version}</a> '
            f'(<a href="dbt/info-schema/{version}.json">raw</a>)</h4>',
            "    <ul>",
            '      <li><a href="dbt/info-schema/erd/index.html">ERD</a></li>',
        ]
        for table in index["tables"]:
            if version in table["versions"]:
                name = html.escape(table["name"])
                lines.append(
                    f'      <li><a href="dbt/info-schema/{name}/{version}/index.html">{name}</a> '
                    f'(<a href="dbt/info-schema/{name}/{version}.json">raw</a>)</li>'
                )
        lines.append("    </ul>")
    lines.append("    " + END)
    return "\n".join(lines)


def update_root_page(index: dict) -> None:
    page = ROOT_PAGE.read_text()
    section = root_section(index)
    if START in page and END in page:
        head, rest = page.split(START, 1)
        _, tail = rest.split(END, 1)
        # `head` ends with the indent of the start marker; `section` starts
        # with the marker, so drop that indent to avoid doubling it.
        page = head.rstrip(" ") + "    " + section.lstrip() + tail
    else:
        marker = "  </main>"
        if marker not in page:
            sys.exit("index.html has no </main> to insert the Info Schema section before")
        page = page.replace(marker, "    " + section.lstrip() + "\n" + marker, 1)
    ROOT_PAGE.write_text(page)


def main() -> None:
    index = load_index()
    remove_stale_tables(index)
    build_schema_pages(index)
    build_erd_pages(index)
    update_root_page(index)


if __name__ == "__main__":
    main()
