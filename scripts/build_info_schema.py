#!/usr/bin/env python3
"""Build the HTML for the info schema from the raw files in dbt/info-schema/.

Run by the sync workflow in dbt-labs/fs after it copies in the raw files, so one
PR carries both. Input, generated by `cargo run -p dbt-index-core --example info_schema_docs` (never edited
by hand):
  dbt/info-schema/index.json
  dbt/info-schema/v1.json              every table in one schema
  dbt/info-schema/<table>/v1.json
  dbt/info-schema/graph.json           tables and relationships, for the interactive ERD

Output:
  dbt/info-schema/v1/index.html (+ css, js)            json-schema-for-humans
  dbt/info-schema/<table>/v1/index.html (+ css, js)    json-schema-for-humans
  dbt/info-schema/erd/index.html                       interactive ERD (static/erd/)
  the "Info Schema" section at the top of the root index.html

Run from anywhere: `make info_schema_html`. Needs `json-schema-for-humans` 1.5.1.
"""

import html
import json
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DBT = REPO / "dbt"
INFO = DBT / "info-schema"
ROOT_PAGE = REPO / "index.html"

# The interactive ERD. Its code is built from scripts/erd-app/ into static/erd/
# and committed, so the page loads nothing from a CDN.
EXPLORER_TEMPLATE = Path(__file__).with_name("erd_explorer.html")

START = "<!-- info-schema:start -->"
END = "<!-- info-schema:end -->"

def load_index() -> dict:
    return json.loads((INFO / "index.json").read_text())


def remove_stale_tables(index: dict) -> None:
    """Drop directories of tables that left the index.

    The sync deletes a removed table's JSON but keeps the HTML it excludes
    from `--delete`, so a leftover directory holds only generated files.
    """
    keep = {t["name"] for t in index["tables"]} | {v["name"] for v in index["versions"]} | {"erd"}
    for path in INFO.iterdir():
        if path.is_dir() and path.name not in keep:
            shutil.rmtree(path)


def render_schema_page(schema: Path, out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    # No footer: it carries the generation date, which would change every page
    # on every run.
    subprocess.run(
        ["generate-schema-doc", "--config", "with_footer=false", str(schema), str(out)],
        check=True,
    )


def build_schema_pages(index: dict) -> None:
    for table in index["tables"]:
        for version in table["versions"]:
            render_schema_page(
                INFO / table["name"] / f"{version}.json",
                INFO / table["name"] / version / "index.html",
            )
    for version in index["versions"]:
        render_schema_page(
            INFO / f"{version['name']}.json", INFO / version["name"] / "index.html"
        )


def build_explorer_page(index: dict) -> None:
    """The interactive ERD."""
    # Everything under erd/ is generated.
    shutil.rmtree(INFO / "erd", ignore_errors=True)
    out = INFO / "erd" / "index.html"
    out.parent.mkdir(parents=True, exist_ok=True)
    up = "../" * len(out.relative_to(REPO).parts[:-1])  # to the repo root
    if "graph" not in index:
        sys.exit("index.json has no 'graph' entry: regenerate the info schema files")
    page = EXPLORER_TEMPLATE.read_text()
    for token, value in {
        "__UP__": up,
        "__GRAPH__": f"{up}dbt/{index['graph']}",
        "__BASE__": f"{up}dbt/info-schema/",
    }.items():
        page = page.replace(token, value)
    out.write_text(page)


def version_key(version: str) -> int:
    return int(version.lstrip("v"))


def root_section(index: dict) -> str:
    """The Info Schema entry of the root page: one line per version.

    Each line links to the page and the raw file of the whole schema, and to
    the ERD. The tables are reached from the version page.
    """
    versions = sorted(
        (v["name"] for v in index["versions"]), key=version_key, reverse=True
    )
    lines = [START, "    <h3>Info Schema</h3>", "    <ul>"]
    for version in versions:
        lines.append(
            f'      <li><a href="dbt/info-schema/{version}/index.html">{version}</a> '
            f'(<a href="dbt/info-schema/{version}.json">raw</a>) '
            '(<a href="dbt/info-schema/erd/index.html">ERD</a>)</li>'
        )
    lines += ["    </ul>", "    " + END]
    return "\n".join(lines)


def update_root_page(index: dict) -> None:
    """Put the section first, right under the page title."""
    page = ROOT_PAGE.read_text()
    if START in page and END in page:
        head, rest = page.split(START, 1)
        _, tail = rest.split(END, 1)
        page = head.rstrip(" ") .rstrip("\n") + "\n" + tail.lstrip("\n")
    anchor = "    <h1>dbt JSON Schemas</h1>\n"
    if anchor not in page:
        sys.exit("index.html has no <h1>dbt JSON Schemas</h1> to insert the Info Schema section after")
    page = page.replace(anchor, anchor + "\n    " + root_section(index).lstrip() + "\n", 1)
    ROOT_PAGE.write_text(page)


def main() -> None:
    index = load_index()
    remove_stale_tables(index)
    build_schema_pages(index)
    build_explorer_page(index)
    update_root_page(index)


if __name__ == "__main__":
    main()
